def causal_rolling_mean(prob,group,k=3):
    """Simple unoptimized baseline, using present and PAST only per cycle."""
    p=np.asarray(prob,float)
    g=np.asarray(group)
    if p.ndim!=2 or p.shape[1]!=3 or len(g)!=len(p):
        raise ValueError("Expected ordered N x 3 probabilities and groups")
    out=np.empty_like(p)
    for group_id in np.unique(g):
        indices=np.flatnonzero(g==group_id)
        if not len(indices):continue
        if indices[-1]-indices[0]+1!=len(indices):
            raise ValueError("Group must be contiguous")
        for local_i,global_i in enumerate(indices):
            out[global_i]=np.mean(p[indices[max(0,local_i-k+1):local_i+1]],axis=0)
    return out


def true_transition_delays(y,pred,group,sample_time):
    """Causal first target-state detection, bounded by the next truth change.

    No adjacent groups linked. Delay measured from trailing WINDOW END; the
    underlying telemetry has minute timestamps and windows stride=4 minutes.
    Missing detections are counted and not silently dropped from reporting.
    """
    y=np.asarray(y,int);pred=np.asarray(pred,int)
    group=np.asarray(group);sample_time=np.asarray(sample_time,int)
    if not (len(y)==len(pred)==len(group)==len(sample_time)):
        raise ValueError("Different sequence lengths")
    changes=[]
    for g in np.unique(group):
        idx=np.flatnonzero(group==g)
        if not len(idx):continue
        if idx[-1]-idx[0]+1 != len(idx):
            raise ValueError("Group not a contiguous evaluation sequence")
        if np.any(np.diff(sample_time[idx])<=0):
            raise ValueError("Out-of-order timestamps")
        truth=y[idx]
        starts=np.r_[0,np.flatnonzero(truth[1:]!=truth[:-1])+1]
        ends=np.r_[starts[1:],len(idx)]
        for t in range(1,len(starts)):
            onset=int(starts[t])
            end=int(ends[t])
            wanted=int(truth[onset])
            start_index=int(idx[onset])
            candidate=idx[onset:end]
            matches=candidate[pred[candidate]==wanted]
            if len(matches):
                found=int(matches[0])
                delay=int(sample_time[found]-sample_time[start_index])
                assert delay>=0
            else:
                found=None;delay=None
            changes.append({
                "cycle_id":int(g),"from":int(truth[onset-1]),
                "to":wanted,"window_onset_index":start_index,
                "window_detection_index":found,
                "delay_minutes":delay,
                "transition_detected":delay is not None})
    detected=[int(v["delay_minutes"]) for v in changes if v["transition_detected"]]
    # Predicted-state flip while real state stayed unchanged. This reflects
    # state chatter, not necessarily a newly arising real event.
    spurious=int(np.sum((pred[1:]!=pred[:-1])&(y[1:]==y[:-1])&
                       (group[1:]==group[:-1])))
    changes_by_target={}
    for target,name in [(0,"healthy"),(1,"degraded"),(2,"fault")]:
        subset=[q for q in changes if q["to"]==target]
        hits=[q["delay_minutes"] for q in subset if q["transition_detected"]]
        changes_by_target[name]={"events":len(subset),"detected":len(hits),
                  "missed":len(subset)-len(hits),
                  "median_delay_minutes":float(np.median(hits)) if hits else None}
    return {
      "true_change_events":len(changes),
      "transition_detected":len(detected),
      "transition_missed":len(changes)-len(detected),
      "detected_fraction":len(detected)/len(changes) if changes else None,
      "median_detected_delay_minutes":float(np.median(detected)) if detected else None,
      "mean_detected_delay_minutes":float(np.mean(detected)) if detected else None,
      "p90_detected_delay_minutes":float(np.percentile(detected,90)) if detected else None,
      "spurious_prediction_state_switches":spurious,
      "by_target":changes_by_target,
      "events":changes
    }


def quality(y,p,group,sample_time):
    q=evaluation(y,p)
    pred=np.argmax(p,axis=1)
    q["balanced_accuracy"]=float(balanced_accuracy_score(y,pred))
    q["confusion_matrix"]=confusion_matrix(y,pred,labels=[0,1,2]).tolist()
    q["state_counts_truth"]=np.bincount(y,minlength=3).tolist()
    q["state_counts_predicted"]=np.bincount(pred,minlength=3).tolist()
    q["temporal"]=true_transition_delays(y,pred,group,sample_time)
    return q


def timer(fn,repeats):
    # Executes on same CPU and input. Warmup removes first call overhead.
    fn()
    t=[]
    for _ in range(repeats):
        start=time.perf_counter()
        fn()
        t.append((time.perf_counter()-start)*1000.)
    a=np.asarray(t,float)
    return {
       "median_ms":float(np.median(a)),
       "q25_ms":float(np.percentile(a,25)),
       "q75_ms":float(np.percentile(a,75)),
       "repeats":len(t)
    }


def plot(report,out):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    methods=list(report["methods"])
    data=[report["methods"][x] for x in methods]
    labels=["Static","Causal mean-3","HMM","HMM + fusion"]
    fig,ax=plt.subplots(figsize=(9.5,6))
    for idx,item in enumerate(data):
        runtime=report["timings"][methods[idx]]["median_ms"]
        ax.scatter(runtime,item["brier"],s=90+65*item["macro_f1"],alpha=.85)
        ax.annotate(f"{labels[idx]} / F1 {item['macro_f1']:.3f}",
             (runtime,item["brier"]),xytext=(6,7 if idx%2 else -17),
             textcoords="offset points",fontsize=10)
    ax.set_xlim(left=0)
    ax.set_xlabel("Frozen pipeline prediction wall clock per 272 windows (ms)")
    ax.set_ylabel("3-state multiclass Brier (lower is better)")
    ax.set_title("Frozen synthetic state inference: cost vs probability quality")
    ax.grid(alpha=.25)
    fig.tight_layout()
    fig.savefig(out/"cost_vs_probability_quality.png",dpi=175)
    plt.close(fig)

    fig,ax=plt.subplots(figsize=(10,5.5))
    x=np.arange(len(methods))
    recall=np.array([item["recalls"] for item in data])
    for i,label in enumerate(("Healthy","Degraded","Fault")):
        ax.bar(x+(i-1)*.22,recall[:,i],width=.21,label=label)
    ax.set_xticks(x,labels)
    ax.set_ylim(0,1.09)
    ax.set_ylabel("Recall on simulated test")
    ax.set_title("Per-state Recall: distinguish rare fault from normal transitions")
    ax.legend()
    ax.grid(axis="y",alpha=.24)
    fig.tight_layout()
    fig.savefig(out/"state_recall_comparison.png",dpi=175)
    plt.close(fig)

    # A miss must not be interpreted as zero detection latency.
    fig,ax=plt.subplots(figsize=(10,5.5))
    elapsed=[item["temporal"]["median_detected_delay_minutes"] for item in data]
    misses=[item["temporal"]["transition_missed"] for item in data]
    ax.bar(labels,[v if v is not None else 0 for v in elapsed])
    for i,(val,miss) in enumerate(zip(elapsed,misses)):
        ax.annotate(f"missed {miss}",(i,float(val or 0)),xytext=(0,4),
                    ha="center",textcoords="offset points",fontsize=9)
    ax.set_ylabel("Median delay among DETECTED transitions (minutes)")
    ax.set_title("Simulated state transition delay; miss counts included")
    ax.grid(axis="y",alpha=.24)
    fig.tight_layout()
    fig.savefig(out/"state_transition_delay.png",dpi=175)
    plt.close(fig)


def run(out_path):
    out=Path(out_path);out.mkdir(parents=True,exist_ok=True)
    spec_bytes=SPEC.read_bytes()
    config=json.loads(spec_bytes)
    original_metrics=json.loads((FROZEN/"metrics.json").read_text())
    # ONLY load this project's trusted, CI-generated model bundle.
    saved=joblib.load(FROZEN/"model_bundle.joblib")
    assert saved["spec_sha256"]==original_metrics["protocol_sha256"]
    data=generate()
    windows,frame=make_windows(data)
    X,names=highdim_features(windows)
    if names!=saved["feature_names"]:
        raise RuntimeError("Frozen feature schema changed")
    mission=frame.mission_id.to_numpy(int)
    test=(mission==3)
    cycle=frame.cycle_id.to_numpy(int)[test]
    truth=frame.health_state_simulated.to_numpy(int)[test]
    timestamps=frame.sample_in_mission.to_numpy(int)[test]
    wt=windows[test]
    Xt=X[test]
    assert len(truth)==config["data"]["windows_expected"]==272
    assert len(np.unique(cycle))==4
    model=saved["hierarchical"]
    gamma=.6
    memory=.5
    # Pre-registered exact inference definitions.
    def do_static():return predict_hierarchical(model,Xt)
    p_static=do_static()
    def do_roll():return causal_rolling_mean(p_static,cycle,k=3)
    p_roll=do_roll()
    def do_hmm():return filter_groups(model,p_static,cycle,gamma=gamma,memory=memory)
    p_hmm=do_hmm()
    anomaly_probs=saved["anomaly_detector"].predict_proba(
                 wt.reshape(len(wt),-1))[:,1]
    def do_fusion():return saved["fusion"].predict_proba(stacking_inputs(p_hmm,anomaly_probs))
    p_fusion=do_fusion()
    actual={
      "static_hierarchical":p_static,
      "causal_rolling_mean_3":p_roll,
      "causal_hmm_gamma_0.6_memory_0.5":p_hmm,
      "hmm_plus_anomaly_late_fusion":p_fusion
    }
    for k,arr in actual.items():
        if not np.isfinite(arr).all() or np.any(arr<0) or not np.allclose(arr.sum(axis=1),1,atol=1e-8):
            raise RuntimeError("Invalid probability distribution for "+k)
    scores={key:quality(truth,value,cycle,timestamps) for key,value in actual.items()}
    previous=[
     ("base_static_state_metrics","static_hierarchical"),
     ("base_hmm_state_metrics","causal_hmm_gamma_0.6_memory_0.5"),
     ("late_fusion_state_metrics","hmm_plus_anomaly_late_fusion")
    ]
    for old,new in previous:
        for metric in ("macro_f1","brier","nll"):
            if not np.isclose(scores[new][metric],original_metrics[old][metric],atol=1e-10):
                raise AssertionError(f"Frozen model metric not reproduced: {new}/{metric}")
    # Stage timings: p_static includes classifier+calibration; other reported
    # model rows reflect p_static stage plus their incremental stage.
    repeats=config["timing"]["repeats"]
    stages={
        "hierarchical_classifier":timer(do_static,repeats),
        "causal_average_additional":timer(do_roll,repeats),
        "hmm_forward_filter_additional":timer(do_hmm,repeats),
        "anomaly_rf_probability_additional":timer(
             lambda:saved["anomaly_detector"].predict_proba(wt.reshape(len(wt),-1))[:,1],repeats),
        "late_fusion_predict_additional":timer(do_fusion,repeats)
    }
    def do_full_hmm():
        return filter_groups(model,do_static(),cycle,gamma=gamma,memory=memory)
    def do_full_fused():
        stat=do_static()
        hmm=filter_groups(model,stat,cycle,gamma=gamma,memory=memory)
        a=saved["anomaly_detector"].predict_proba(wt.reshape(len(wt),-1))[:,1]
        return saved["fusion"].predict_proba(stacking_inputs(hmm,a))
    full_methods={
        "static_hierarchical":do_static,
        "causal_rolling_mean_3":lambda:causal_rolling_mean(do_static(),cycle,k=3),
        "causal_hmm_gamma_0.6_memory_0.5":do_full_hmm,
        "hmm_plus_anomaly_late_fusion":do_full_fused
    }
    timings={key:timer(fn,repeats) for key,fn in full_methods.items()}
    feedback_truth=frame.operator_score_simulated.to_numpy(float)[test]
    corrected_weights=np.asarray(saved["corrected_score_mapping"],float)
    prior_weights=np.asarray(saved["default_score_mapping"],float)
    feedback={
      "label_origin":"FULLY_SIMULATED_OPERATOR_SCORE",
      "default_MAE":float(mean_absolute_error(feedback_truth,p_fusion@prior_weights)),
      "corrected_MAE":float(mean_absolute_error(feedback_truth,p_fusion@corrected_weights)),
      "score_mapping_weight_vectors":{"default":prior_weights.tolist(),
                                      "corrected":corrected_weights.tolist()},
      "note":"Operator feedback in this MVP is generated and is not a real expert health score"}
    if not np.isclose(feedback["corrected_MAE"],
                      original_metrics["simulated_feedback"]["corrected_score_test_mae"],
                      atol=1e-9):
        raise AssertionError("Frozen score mapping metrics changed")
    report={
      "study":"Frozen SYNTHETIC satellite 3-state HMM/fusion module multiobjective diagnostic",
      "simulation_only":True,
      "original_mvp_test_metrics_reproduced":True,
      "no_new_hyperparameter_tuning_on_test":True,
      "original_synthetic_spec_sha256":original_metrics["protocol_sha256"],
      "research_protocol_sha256":hashlib.sha256(spec_bytes).hexdigest(),
      "state_truth":["simulated_healthy","simulated_degraded","simulated_fault"],
      "synthetic_data":{"test_windows":len(truth),
                        "independent_test_cycles":len(np.unique(cycle)),
                        "state_counts":np.bincount(truth,minlength=3).tolist(),
                        "number_true_state_transitions":scores["static_hierarchical"]["temporal"]["true_change_events"],
                        "stride_minutes":4},
      "methods":scores,
      "timings":timings,
      "incremental_stages":stages,
      "simulated_health_score":feedback,
      "limitations":[
        "Every state and health score is generated by the frozen simulator, not actual expert-labeled spacecraft fault truth",
        "The simulation uses four test cycles from one simulated mission; transitions are repeated by construction",
        "This is existing discriminative hierarchical classification with causal HMM forward filtering; not a separately implemented full dynamic Bayesian network",
        "Fusion classifier and probability calibrators were trained on the same preexisting calibration mission; this is diagnostic evidence, not a new model-selection test",
        "A causal rolling mean is a simple fixed history baseline; it is not trained or retuned",
        "Timing on 272 batch windows and single CI machine measures module compute, not actual on-orbit realtime latency",
        "No post-hoc choice of smoothing gamma/memory using the heldout test",
        "OPS-SAT 64-feature-budget decision belongs to a distinct real 2578-dimensional experiment; frozen synthetic 400-feature selector is unchanged",
        "Patent-sensitive mechanisms for targeted supervised updates are not present here"
      ]
    }
    (out/"metrics.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    rows=[]
    for k,q in scores.items():
        tm=q["temporal"]
        rows.append({
         "method":k,"macro_f1":q["macro_f1"],"brier":q["brier"],
         "nll":q["nll"],"balanced_accuracy":q["balanced_accuracy"],
         "healthy_recall":q["recalls"][0],
         "degraded_recall":q["recalls"][1],"fault_recall":q["recalls"][2],
         "state_changes":tm["true_change_events"],
         "detected_transitions":tm["transition_detected"],
         "missed_transitions":tm["transition_missed"],
         "median_detected_delay_minutes":tm["median_detected_delay_minutes"],
         "p90_detected_delay_minutes":tm["p90_detected_delay_minutes"],
         "spurious_prediction_switches":tm["spurious_prediction_state_switches"],
         "inference_272_windows_median_ms":timings[k]["median_ms"],
         "inference_per_window_ms":timings[k]["median_ms"]/len(truth)
        })
    pd.DataFrame(rows).to_csv(out/"ablation_table.csv",index=False)
    pred=pd.DataFrame({
      "cycle_id":cycle,
      "sample_in_mission":timestamps,
      "simulated_state_truth":truth,
      "simulated_anomaly_truth":frame.anomaly_simulated.to_numpy(int)[test],
    })
    for k,p in actual.items():
        pred[k+"_prediction"]=p.argmax(axis=1)
        for c,label in enumerate(("healthy","degraded","fault")):
            pred[k+"_p_"+label]=p[:,c]
    pred.to_csv(out/"state_predictions.csv",index=False)
    plot(report,out)
    md=[
      "# HMM 与概率融合的目的导向评估（完全模拟数据）",
      "",
      "**所有健康/退化/故障、异常和人工评分都是模拟真值。本实验是冻结 MVP 的多指标消融，不是 OPS-SAT 真实三级健康状态验证。**",
      "",
      "不训练新模型，不动交付版；直接读取保存的两级分类器、HMM、异常检测器及融合模型，对测试任务段进行同一批样本的复现。",
      f"测试含 {len(truth)} 个窗口、{len(np.unique(cycle))} 条模拟周期，每 4 分钟一个窗口。",
      "",
      "| 方法 | Macro-F1 | Brier ↓ | NLL ↓ | Healthy Recall | Degraded Recall | Fault Recall | 漏检切换 | 已检出切换中位延迟(min) | 272窗口推断中位(ms) |",
      "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    labels={"static_hierarchical":"静态两级状态",
            "causal_rolling_mean_3":"静态+历史均值(3)",
            "causal_hmm_gamma_0.6_memory_0.5":"静态+HMM",
            "hmm_plus_anomaly_late_fusion":"静态+HMM+异常融合"}
    for k,q in scores.items():
        t=q["temporal"]
        md.append(
          f"| {labels[k]} | {q['macro_f1']:.4f} | {q['brier']:.4f} | {q['nll']:.4f} | "
          f"{q['recalls'][0]:.4f} | {q['recalls'][1]:.4f} | {q['recalls'][2]:.4f} | "
          f"{t['transition_missed']}/{t['true_change_events']} | "
          f"{t['median_detected_delay_minutes'] if t['median_detected_delay_minutes'] is not None else 'N/A'} | {timings[k]['median_ms']:.3f} |")
    md.extend(["",
         f"模拟评分：默认健康分 MAE={feedback['default_MAE']:.3f}，"
         f"使用模拟人工评分校正后 MAE={feedback['corrected_MAE']:.3f}。",
         "",
         "![推断开销与概率误差](cost_vs_probability_quality.png)",
         "",
         "![各类状态召回率](state_recall_comparison.png)",
         "",
         "![状态切换延迟](state_transition_delay.png)",
         "",
         "时间延迟定义为：在同一模拟周期内，真实状态变更后直到首次输出该目标类别的时间（4分钟窗口步长）；",
         "未检出的转移单独报告，不计为0延迟。跨周期不连边。",
         "真实 OPS-SAT 目前没有物理三级状态标注，因此本结果不得用于宣称真实卫星故障状态识别率。",
         "所有模型参数均来自原冻结模拟实验，未因本次测试结果调参。",
         "",
         "64维预算固定为此前真实 OPS-SAT 2578维多尺度特征选择的工程配置，实际选中37维；",
         "本次复现沿用冻结模拟模型的既有400维特征输入和两级选择结果，不将两个任务的特征预算强制混淆。",
         ""
    ])
    (out/"RESULTS.md").write_text("\n".join(md),encoding="utf-8")
    print(json.dumps({"method_metrics":[{key:r[key] for key in ("method","macro_f1","brier",
         "nll","detected_transitions","missed_transitions","median_detected_delay_minutes",
         "spurious_prediction_switches","inference_272_windows_median_ms")} for r in rows],
         "stage_timing":stages,"simulated_health_score":feedback},indent=2))
    return report


